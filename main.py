def print_console(s, index, state, value, ending=False, ending_status=False):
    print("\033[2J\033[H", end="")
    print(("\n" + "░"*size_ligne)*3)
    if size_ligne > 180:
        print(title)
    elif size_ligne > 100:
        print(title_light)
    else:
        print(title_tiny)
    print(("░" * size_ligne) * 3)
    print(f"   state : {state}   value : {value}")
    print("░"*size_ligne+ "\n\n")
    print(s + "\n" + index*" " + "↑")
    if ending:
        print(f"\n ending with status {ending_status}")

